// Writes src/posterPlaceholders.ts: a tiny blurred copy of each persona image
// (public/images/art/user-*.png) as a data URI, for the `poster` of the videos
// of the home page. Run it again when the art changes:
//
//   node scripts/generate-poster-placeholders.mjs [--width 32] [--quality 0.8]
//
// A data URI is in the HTML, so the poster shows from the first paint, also
// without JavaScript, and it costs no request. At 32 px wide it is about
// 1.2 KB. The browser scales it up to the size of the video, which blurs it.
//
// It uses the browser of Playwright to scale and to encode the image. Set
// CHROMIUM_PATH to use another one.
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {chromium} from '@playwright/test';

const argv = process.argv.slice(2);
const option = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i === -1 ? fallback : Number(argv[i + 1]);
};
const WIDTH = option('width', 32);
const QUALITY = option('quality', 0.8);

const ART = new URL('../public/images/art/', import.meta.url);
const OUTPUT = new URL('../src/posterPlaceholders.ts', import.meta.url);

// user-beginner.png, but not user-beginner.small.png.
const slugs = readdirSync(ART)
  .map(name => /^user-([a-z]+)\.png$/.exec(name)?.[1])
  .filter(Boolean)
  .sort();

// Chrome writes a color profile (sRGB, 460 bytes) into each WebP, which is
// more than the pixels. An image without a profile is sRGB, so cut the chunk
// out, and the flag for it in the header (`VP8X`). With no other flag left,
// the header has nothing to say, so cut that out too.
function withoutColorProfile(webp) {
  const chunks = [];
  // After "RIFF", the size and "WEBP".
  for (let offset = 12; offset < webp.length;) {
    const type = webp.toString('ascii', offset, offset + 4);
    const size = webp.readUInt32LE(offset + 4);
    // A chunk has an even size, with a byte of padding after an odd one.
    const end = offset + 8 + size + (size % 2);
    let chunk = webp.subarray(offset, end);
    if (type === 'VP8X') {
      chunk = Buffer.from(chunk);
      chunk[8] &= ~0x20;
      if (chunk[8] === 0) chunk = Buffer.alloc(0);
    }
    if (type !== 'ICCP') chunks.push(chunk);
    offset = end;
  }
  const body = Buffer.concat([Buffer.from('WEBP'), ...chunks]);
  const header = Buffer.alloc(8);
  header.write('RIFF');
  header.writeUInt32LE(body.length, 4);
  return Buffer.concat([header, body]);
}

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
});
const page = await browser.newPage();
const placeholders = {};
for (const slug of slugs) {
  const png = readFileSync(new URL(`user-${slug}.png`, ART)).toString('base64');
  placeholders[slug] = await page.evaluate(
    async ([png, width, quality]) => {
      const image = new Image();
      image.src = `data:image/png;base64,${png}`;
      await image.decode();
      const height = Math.round(
        (width * image.naturalHeight) / image.naturalWidth,
      );

      // One jump from 2629 px to 32 px skips most of the pixels. Halve the size
      // until the next step is the target: each step averages 2x2 pixels, which
      // is close to the average of the whole area.
      let source = image;
      let w = image.naturalWidth;
      let h = image.naturalHeight;
      while (w / 2 > width) {
        w = Math.max(width, Math.round(w / 2));
        h = Math.max(height, Math.round(h / 2));
        const step = document.createElement('canvas');
        step.width = w;
        step.height = h;
        const stepContext = step.getContext('2d');
        stepContext.imageSmoothingQuality = 'high';
        stepContext.drawImage(source, 0, 0, w, h);
        source = step;
      }
      const canvas = document.createElement('canvas');
      canvas.width = width;
      canvas.height = height;
      const context = canvas.getContext('2d');
      context.imageSmoothingQuality = 'high';
      context.drawImage(source, 0, 0, width, height);
      return canvas.toDataURL('image/webp', quality);
    },
    [png, WIDTH, QUALITY],
  );
  const [, base64] = placeholders[slug].split(',');
  placeholders[slug] = `data:image/webp;base64,${withoutColorProfile(
    Buffer.from(base64, 'base64'),
  ).toString('base64')}`;
  console.log(`${slug}: ${placeholders[slug].length} characters`);
}
await browser.close();

const entries = Object.entries(placeholders)
  // A string this long goes on a line of its own, as Prettier writes it.
  .map(([slug, url]) => `  ${slug}:\n    '${url}',`)
  .join('\n');
writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-poster-placeholders.mjs from
// public/images/art/user-*.png. Do not edit: run the script again.
//
// A blurred copy of each persona image, ${WIDTH} px wide, as a data URI. The
// \`poster\` of a video on the home page: it is in the HTML, so it shows from
// the first paint and costs no request.
export const POSTER_PLACEHOLDERS = {
${entries}
} as const;
`,
);
